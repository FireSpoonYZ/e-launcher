import assert from "node:assert/strict";
import { createExecutionStatus } from "./execution-status.js";

const events = [];
const accept = createExecutionStatus(event => events.push(event));
accept({ type:"agent_start" });
accept({ type:"message_update", assistantMessageEvent:{ type:"thinking_delta", delta:"private reasoning" } });
assert.equal(events.length, 1, "thinking deltas are coalesced and never expose reasoning text");
accept({ type:"message_update", assistantMessageEvent:{ type:"text_delta", delta:"hello" } });
assert.equal(events.at(-1).phase, "responding");
accept({ type:"tool_execution_start", toolName:"shower", args:{secret:"hidden"} });
assert.equal(events.at(-1).toolName, "shower");
accept({ type:"auto_retry_start", attempt:2, maxAttempts:3, delayMs:1200, errorMessage:"private endpoint" });
assert.deepEqual(events.at(-1), {type:"status", phase:"retrying", attempt:2, maxAttempts:3, delayMs:1200});
accept({ type:"auto_retry_end", success:true, attempt:1 });
assert.equal(events.at(-1).phase, "retrying", "stale retry does not clear the active attempt");
accept({ type:"message_update", assistantMessageEvent:{type:"text_delta",delta:"resumed"} });
accept({ type:"auto_retry_end", success:true, attempt:2 });
assert.equal(events.at(-1).phase, "responding", "retry completion must not overwrite response progress");
accept({ type:"auto_compaction_start" });
assert.equal(events.at(-1).phase, "compacting");
accept({ type:"auto_compaction_end", aborted:false });
assert.equal(events.at(-1).phase, "thinking");
accept({ type:"auto_compaction_start" });
accept({ type:"auto_compaction_end", aborted:true });
assert.equal(events.at(-1).phase, "thinking", "canceling compaction does not claim the whole run stopped");
accept({ type:"end" });
const count = events.length;
accept({ type:"auto_retry_start", attempt:3 });
accept({ type:"message_update", assistantMessageEvent:{type:"text_delta",delta:"late"} });
assert.equal(events.length,count);
assert(!JSON.stringify(events).includes("private"));
assert(!JSON.stringify(events).includes("hidden"));
console.log("execution status checks passed");
