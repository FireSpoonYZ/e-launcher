import assert from 'node:assert/strict';
import { requestBots, validateCall, roleInstruction, ACTIONS } from '../pi-runtime/extensions/session-bots/protocol.js';
let checks = 0;
function check(test) { test(); checks++; }
const operation = () => ({ id: 'host-request', controller: new AbortController(), nativeCalls: new Map() });
check(() => assert.equal(ACTIONS.includes('delete'), false));
for (const action of ['delete', 'delete_bot', 'archive', 'update_other']) check(() => assert.throws(() => validateCall({ action })));
for (const field of ['callerId', 'ownerId', 'sessionId', 'conversationId', 'requestId'])
  check(() => assert.throws(() => validateCall({ action: 'self', [field]: 'victim' })));
check(() => assert.throws(() => validateCall({ action: 'send', targetId: '', message: 'a' })));
check(() => assert.throws(() => validateCall({ action: 'send', targetId: 'b', message: 'x'.repeat(16001) })));
check(() => assert.throws(() => validateCall({ action: 'role', rolePrompt: 42 })));
check(() => assert.equal(validateCall({ action: 'role', rolePrompt: '' }).rolePrompt, ''));
const profile = { id: 'a', name: '研究员', rolePrompt: '研究 Rust 项目。' };
const prompt = roleInstruction({ systemPrompt: 'GLOBAL RULES' }, profile).systemPrompt;
check(() => assert.ok(prompt.startsWith('GLOBAL RULES') && prompt.includes(profile.rolePrompt)));
check(() => assert.equal(roleInstruction({ systemPrompt: 'global' }, undefined), undefined));
const op = operation(); const sent = [];
const pending = requestBots(v => sent.push(v), op, { action: 'send', targetId: 'b', message: 'task' }, undefined, 'tool-1');
check(() => assert.equal(sent.length, 1));
check(() => assert.equal(sent[0].id, 'host-request'));
check(() => assert.equal(sent[0].callId, 'bots:tool-1'));
check(() => assert.equal(sent[0].type, 'bots_request'));
check(() => assert.throws(() => requestBots(v => sent.push(v), op, { action: 'self' }, undefined, 'tool-1')));
op.nativeCalls.get('bots:tool-1').finish(undefined, { id: 'delivery-1', status: 'queued' });
const response = await pending;
check(() => assert.equal(response.id, 'delivery-1'));
check(() => assert.equal(op.nativeCalls.size, 0));
const abortOp = operation();
const abortPending = requestBots(() => {}, abortOp, { action: 'self' }, undefined, 'cancel');
abortOp.controller.abort(new Error('stopped'));
await assert.rejects(abortPending, /stopped/); checks++;
check(() => assert.equal(abortOp.nativeCalls.size, 0));
check(() => assert.throws(() => requestBots(() => {}, abortOp, { action: 'self' }, undefined, 'after-cancel')));
const timeoutOp = operation(); let transmitted = 0;
const timed = requestBots(() => { transmitted++; }, timeoutOp, { action: 'create', name: 'new' }, undefined, 'timeout', 5);
await assert.rejects(timed, /结果不确定/); checks++;
check(() => assert.equal(transmitted, 1));
check(() => assert.equal(timeoutOp.nativeCalls.size, 0));
const failedSend = operation();
await assert.rejects(requestBots(() => { throw new Error('socket closed'); }, failedSend, { action: 'self' }, undefined, 'socket'), /socket closed/); checks++;
check(() => assert.equal(failedSend.nativeCalls.size, 0));
console.log(`PASS: ${checks} protocol assertions (no SDK or provider loaded)`);
